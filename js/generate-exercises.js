const fs = require('fs');

function esc(s) {
  if (!s) return '';
  return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
}

function makeEntry(key, links, exercises) {
  let s = `  "${key}": {\n    links: [\n`;
  for (const l of links) {
    const url = l.url === null ? 'null' : `"${esc(l.url)}"`;
    s += `      { name: "${esc(l.name)}", url: ${url} },\n`;
  }
  s += `    ],\n    exercises: [\n`;
  for (const e of exercises) {
    s += `      { question: "${esc(e.q)}", answer: "${esc(e.a)}" },\n`;
  }
  s += `    ]\n  },\n`;
  return s;
}

